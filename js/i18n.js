let lang = 'vi';
try {
  const saved = localStorage.getItem('cd-sketchpad:lang');
  if (saved === 'vi' || saved === 'en') lang = saved;
} catch {
  /* storage unavailable */
}

export function getLang() {
  return lang;
}

export function setLang(l) {
  lang = l === 'en' ? 'en' : 'vi';
  try { localStorage.setItem('cd-sketchpad:lang', lang); } catch { /* ignore */ }
  document.documentElement.lang = lang;
}

export function t(key, vars) {
  let s = (STRINGS[lang] && STRINGS[lang][key]) ?? STRINGS.vi[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, v);
  return s;
}

// Fill every [data-i18n] / [data-i18n-title] / [data-i18n-ph] element under `root`.
export function applyI18n(root = document) {
  for (const node of root.querySelectorAll('[data-i18n]')) node.textContent = t(node.dataset.i18n);
  for (const node of root.querySelectorAll('[data-i18n-title]')) {
    node.title = t(node.dataset.i18nTitle);
    node.setAttribute('aria-label', t(node.dataset.i18nTitle));
  }
  for (const node of root.querySelectorAll('[data-i18n-ph]')) node.placeholder = t(node.dataset.i18nPh);
}
